// Writes src/auth/auth.sql: the tables better-auth needs for the plugins in src/auth/options.ts, for an empty database.
// `--check` fails when the file is stale instead of writing it.
import Database from "better-sqlite3";
import { getMigrations } from "better-auth/db/migration";
import { readFileSync, writeFileSync } from "node:fs";
import { authOptions } from "../src/auth/options";

const db = new Database(":memory:");
try {
  const generated = await getMigrations(authOptions(db, { secret: "schema-generation-only-0123456789abcdef", baseUrl: "http://127.0.0.1:3100" }));
  const sql = `-- Generated by better-auth for the plugins in auth/options.ts (pnpm --filter @brain/governor auth:schema). Do not edit by hand.\n${await generated.compileMigrations()}\n`;
  const path = new URL("../src/auth/auth.sql", import.meta.url);
  if (process.argv.includes("--check")) {
    if (readFileSync(path, "utf8") !== sql) throw new Error("auth.sql is stale; run pnpm --filter @brain/governor auth:schema");
  } else writeFileSync(path, sql);
  console.log("auth.sql is current");
} finally {
  db.close();
}
