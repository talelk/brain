// Vendor generation for an EMPTY current-format database only. No historical
// plans are executed or supported; existing application data is never touched.
import Database from "better-sqlite3";
import { getMigrations } from "better-auth/db/migration";
import { writeFileSync, readFileSync } from "node:fs";
import { authOptions } from "../src/modules/identity/options";

const db = new Database(":memory:");
try {
  const generated = await getMigrations(authOptions(db, { secret: "schema-generation-only-0123456789abcdef", baseURL: "http://127.0.0.1:3000" }));
  if (generated.toBeAdded.length || generated.unsafeChanges.length || generated.schemaProblems.length) throw new Error("expected a fresh vendor schema");
  const sql = "-- Generated by Better Auth 1.7.14 for the exact plugins in identity/options.ts.\n-- Fresh current-format initialization only; do not edit by hand.\n" + await generated.compileMigrations() + "\n";
  const path = new URL("../schema/auth.sql", import.meta.url);
  if (process.argv.includes("--check")) {
    if (readFileSync(path, "utf8") !== sql) throw new Error("auth.sql is stale; regenerate the selected vendor's fresh schema");
  } else writeFileSync(path, sql);
  console.log("Better Auth fresh schema generated/verified");
} finally { db.close(); }
