import { test, expect } from "./fixtures";
import { fixtureStarter } from "../support/starter";

test("default administrator changes password and discovers populated starter tasks", async ({ page, governor }) => {
  const brain = governor.app.brain;
  const temporary = "temporary-browser-password-123";
  const result = await brain.bootstrap({ email: "admin@brain.local", password: temporary, name: "My organization", organizationId: "org-local" }, governor.credential);
  const identity = await brain.resolveActor(new Headers({ authorization: `Bearer ${result.sessionToken}` }));
  brain.createWorkspace(identity.actor, { workspaceId: "operations", slug: "My workspace" });
  const bundle = fixtureStarter();
  const release = brain.stageRelease(identity.actor, bundle.documents, bundle.sourceRevision, bundle.scripts, bundle.instructions, bundle.schemas);
  brain.activateRelease(identity.actor, release.digest, null);
  brain.store.control.prepare("INSERT INTO brain_initial_password SELECT userId,password FROM account WHERE userId=? AND providerId='credential'").run(identity.principalId);
  await page.goto(governor.url);
  await page.getByLabel(/^Email/).fill("admin@brain.local");
  await page.getByLabel(/^Password/).fill(temporary);
  await page.getByRole("button", { name: "Sign in", exact: true }).click();
  await expect(page.getByRole("heading", { name: "Welcome to Brain" })).toBeVisible();
  await expect(page.getByRole("button", { name: "Start a task", exact: true })).toHaveCount(0);
  await page.getByLabel(/^Temporary password/).fill(temporary);
  await expect(page.getByText("Use 12–128 characters. Spaces are allowed. Choose a different password from your temporary one.", { exact: true })).toBeVisible();
  await page.getByLabel(/^New password/).fill("short");
  await page.getByRole("button", { name: "Save password and continue" }).click();
  await expect(page.getByRole("alert")).toContainText("12–128 characters");
  await expect(page.getByLabel(/^Temporary password/)).toHaveValue(temporary);
  await page.getByLabel(/^New password/).fill("changed-browser-password-456");
  await page.getByLabel(/^Temporary password/).fill("wrong-temporary-password");
  await page.getByRole("button", { name: "Save password and continue" }).click();
  await expect(page.getByRole("alert")).toContainText("The temporary password is incorrect");
  await expect(page.getByLabel(/^New password/)).toHaveValue("changed-browser-password-456");
  await page.getByLabel(/^Temporary password/).fill(temporary);
  await page.getByRole("button", { name: "Save password and continue" }).click();
  await expect(page.getByRole("heading", { name: "Connect your local model", exact: true })).toBeVisible();
  await page.getByRole("button", { name: "Explore starter tasks", exact: true }).click();
  await expect(page.getByRole("heading", { name: "Choose a task", exact: true })).toBeVisible();
  await expect(page.getByText("Investigate an operational issue").filter({ visible: true }).first()).toBeVisible();
  await expect(page.getByText("Draft a support response").filter({ visible: true }).first()).toBeVisible();
  await expect(page.getByRole("row").filter({ hasText: "Agent smoke" })).toHaveCount(0);
  const signedOut = await page.request.post(`${governor.url}/api/auth/sign-out`, { headers: { origin: governor.url }, data: {} });
  expect(signedOut.ok()).toBe(true);
  await page.reload();
  await page.getByLabel(/^Email/).fill("admin@brain.local");
  await page.getByLabel(/^Password/).fill("changed-browser-password-456");
  await page.getByRole("button", { name: "Sign in", exact: true }).click();
  await expect(page.getByRole("heading", { name: "Choose a task", exact: true })).toBeVisible();
  await expect(page.getByRole("heading", { name: "Welcome to Brain" })).toHaveCount(0);
});
