#!/usr/bin/env python3
"""Generate the Web route index from contracts/v1/ui-screen-contracts.json.

The screen contract is the authority for route ownership, so the route table
that the browser router compiles is generated here instead of being edited in
two places. Each entry keeps its owner and declared queries so a missing typed
read is visible in code review rather than hidden in JSX.
"""

import json
import pathlib

ROOT = pathlib.Path(__file__).resolve().parents[1]
CONTRACT = ROOT / "contracts" / "v1" / "ui-screen-contracts.json"
OUTPUT = ROOT / "apps" / "web" / "src" / "routes" / "index.gen.ts"




def main() -> None:
    contract = json.loads(CONTRACT.read_text(encoding="utf-8"))
    screens = contract["screens"]
    primary = contract["primaryNavigation"]
    lines = [
        "// Generated by scripts/generate_ui_routes.py from contracts/v1/ui-screen-contracts.json.",
        "// Do not edit by hand: route ownership is defined by the screen contract.",
        "",
        "export interface RouteSpec {",
        "  readonly route: string;",
        "  readonly title: string;",
        "  readonly owner: string;",
        "  readonly queries: readonly string[];",
        "  readonly actions: readonly string[];",
        "  readonly navigationGroup: string;",
        "  readonly task: string;",
        "}",
        "",
        "export const ROUTES: readonly RouteSpec[] = [",
    ]
    for screen in screens:
        route = screen["route"]
        fields = {
            "route": route,
            "title": screen["title"],
            "owner": screen["owner"],
            "queries": screen["queries"],
            "actions": screen["actions"],
            "navigationGroup": screen["navigationGroup"],
            "task": screen["task"],
        }
        lines.append("  { " + ", ".join(f"{key}: {json.dumps(value)}" for key, value in fields.items()) + " },")
    lines.append("]")
    lines.append("")
    lines.append("/** Primary product areas; personal settings remain in the account menu. */")
    lines.append(f"export const PRIMARY_NAVIGATION: readonly {{ id: string; label: string; route: string }}[] = {json.dumps([{ 'id': n['id'], 'label': n['label'], 'route': n['entryRoute']} for n in primary])};")
    lines.append("")
    lines.append("export const AREA_NAVIGATION: Readonly<Record<string, readonly { label: string; route: string; adminOnly?: boolean; organizationOnly?: boolean; identityOnly?: boolean }[]>> = " + json.dumps(contract["areaNavigation"]) + ";")
    lines.append(f"export const SECONDARY_NAVIGATION: Readonly<Record<string, string>> = {json.dumps(contract['secondaryNavigation'])};")
    lines.append("")
    lines.append(f"export const READ_ONLY_PRINCIPALS: Readonly<Record<string, string>> = {json.dumps(contract['readOnlyPrincipals'])};")
    lines.append("")
    lines.append(f"export const SHARED_RUN_DETAIL: readonly string[] = {json.dumps(contract['sharedRunDetail'])};")
    lines.append("")
    lines.append(f"export const VIEWPORTS: readonly number[] = {json.dumps(contract['viewports'])};")
    lines.append(f"export const THEMES: readonly string[] = {json.dumps(contract['themes'])};")
    lines.append(f"export const SCREEN_STATES: readonly string[] = {json.dumps(contract['states'])};")
    lines.append("")

    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {OUTPUT.relative_to(ROOT)}: {len(screens)} routes, {len(primary)} primary areas")


if __name__ == "__main__":
    main()
